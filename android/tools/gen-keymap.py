"""Generate EvdevKeymap.kt (Linux evdev key code -> Android KeyEvent keycode).

The table is Android's own frameworks/base/data/keyboards/Generic.kl, which is
what InputReader uses for a keyboard without a vendor-specific layout. Usage:

  android/tools/gen-keymap.py [AOSP]   # default $AOSP or ~/aosp/a17
"""

import os
import re
import sys
from pathlib import Path

aosp = Path(
  sys.argv[1] if len(sys.argv) > 1 else os.environ.get("AOSP", "~/aosp/a17")
).expanduser()
kl = aosp / "frameworks/base/data/keyboards/Generic.kl"
keycodes_h = aosp / "frameworks/native/include/android/keycodes.h"
evdev_h = aosp / "bionic/libc/kernel/uapi/linux/input-event-codes.h"
out = (
  Path(__file__).resolve().parent.parent
  / "input/src/main/kotlin/dev/linuxapk/system/input/EvdevKeymap.kt"
)

keycodes = {
  m[1]: int(m[2])
  for m in re.finditer(r"AKEYCODE_(\w+)\s*=\s*(\d+)", keycodes_h.read_text())
}
evdev_names = {}
for m in re.finditer(
  r"#define\s+((?:KEY|BTN)_\w+)\s+(0x[0-9a-fA-F]+|\d+)", evdev_h.read_text()
):
  evdev_names.setdefault(int(m[2], 0), m[1])

entries = {}
for line in kl.read_text().splitlines():
  f = line.split("#", 1)[0].split()
  if len(f) < 3 or f[0] != "key" or f[1] == "usage":
    continue
  code, label = int(f[1], 0), f[2]
  if label not in keycodes:
    sys.exit(f"unknown keycode label {label!r} in {kl}")
  entries[code] = (label, keycodes[label], f[3:])

rows = []
for code in sorted(entries):
  label, value, flags = entries[code]
  name = evdev_names.get(code, "?")
  note = f" ({' '.join(flags)})" if flags else ""
  rows.append(f"      {code} -> {value} // {name} -> KEYCODE_{label}{note}")

out.write_text(
  f"""// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by android/tools/gen-keymap.py from AOSP
// frameworks/base/data/keyboards/Generic.kl. Do not edit.
package dev.linuxapk.system.input

/** Linux evdev key codes to Android keycodes, as in Android's Generic.kl. */
object EvdevKeymap {{
  /** Number of evdev codes in the table. */
  const val SIZE = {len(rows)}

  /** Android `KeyEvent.KEYCODE_*` for an evdev `KEY_*` code, or 0 (UNKNOWN). */
  fun keycode(evdev: Int): Int =
    when (evdev) {{
{chr(10).join(rows)}
      else -> 0
    }}
}}
"""
)
print(f"wrote {out} ({len(rows)} keys)")
