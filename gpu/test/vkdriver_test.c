static PFN_vkCreateInstance open_hal(const char* path) {
  void* so = NULL;
  void* dla = dlopen("libdl_android.so", RTLD_NOW);
  void* (*get_ns)(const char*) =
    dla ? dlsym(dla, "android_get_exported_namespace") : NULL;
  printf(
    "linker: sphal namespace %s\n",
    get_ns && get_ns("sphal") ? "present" : "ABSENT"
  );
  void* vndk = dlopen("libvndksupport.so", RTLD_NOW);
  void* (*load_sphal)(const char*, int) =
    vndk ? dlsym(vndk, "android_load_sphal_library") : NULL;
  if (load_sphal) so = load_sphal(path, RTLD_NOW | RTLD_LOCAL);
  printf(
    "hal: %s via %s: %s\n", path,
    load_sphal ? "android_load_sphal_library" : "dlopen",
    so ? "loaded" : dlerror()
  );
  if (!so) exit(1);
  hw_module_t* hmi = dlsym(so, "HMI");
  if (!hmi) {
    printf("FAIL: no HMI symbol\n");
    exit(1);
  }
  printf(
    "hal: HMI id=%s name=\"%s\" author=\"%s\" module_api=0x%x\n", hmi->id,
    hmi->name, hmi->author, hmi->module_api_version
  );
  hwvulkan_device_t* hdev = NULL;
  if (hmi->methods->open(hmi, "vk0", (hw_device_t**)&hdev) != 0 || !hdev) {
    printf("FAIL: HAL open(vk0)\n");
    exit(1);
  }
  gipa = hdev->GetInstanceProcAddr;
  return hdev->CreateInstance;
}

static PFN_vkCreateInstance open_loader(void) {
  void* so = dlopen("libvulkan.so", RTLD_NOW);
  if (!so) {
    printf("FAIL: %s\n", dlerror());
    exit(1);
  }
  gipa = (PFN_vkGetInstanceProcAddr)dlsym(so, "vkGetInstanceProcAddr");
  return (PFN_vkCreateInstance)gipa(NULL, "vkCreateInstance");
}

static bool has_ext(const char* name) {
  uint32_t n = 0;
  vkEnumerateDeviceExtensionProperties(pdev, NULL, &n, NULL);
  VkExtensionProperties* e = calloc(n, sizeof(*e));
  vkEnumerateDeviceExtensionProperties(pdev, NULL, &n, e);
  bool found = false;
  for (uint32_t i = 0; i < n; i++) found |= !strcmp(e[i].extensionName, name);
  free(e);
  return found;
}

static uint32_t find_memtype(uint32_t bits, VkMemoryPropertyFlags want) {
  VkPhysicalDeviceMemoryProperties mp;
  vkGetPhysicalDeviceMemoryProperties(pdev, &mp);
  for (uint32_t i = 0; i < mp.memoryTypeCount; i++)
    if ((bits & (1u << i)) && (mp.memoryTypes[i].propertyFlags & want) == want)
      return i;
  return UINT32_MAX;
}

static void setup_device(PFN_vkCreateInstance create_instance) {
  VkApplicationInfo app = {
    .sType = VK_STRUCTURE_TYPE_APPLICATION_INFO,
    .pApplicationName = "vkdriver_test",
    .apiVersion = VK_API_VERSION_1_3,
  };
  VkInstanceCreateInfo ici = {
    .sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO,
    .pApplicationInfo = &app,
  };
  CHECK(create_instance(&ici, NULL, &inst));
  load_instance_fns();

  uint32_t n = 0;
  CHECK(vkEnumeratePhysicalDevices(inst, &n, NULL));
  printf("physical devices: %u\n", n);
  if (!n) {
    printf("FAIL: no physical devices\n");
    exit(1);
  }
  VkPhysicalDevice pds[8];
  n = n > 8 ? 8 : n;
  CHECK(vkEnumeratePhysicalDevices(inst, &n, pds));
  pdev = pds[0];

  VkPhysicalDeviceDriverProperties drv = {
    .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_DRIVER_PROPERTIES
  };
  VkPhysicalDeviceProperties2 p2 = {
    .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2, .pNext = &drv
  };
  vkGetPhysicalDeviceProperties2(pdev, &p2);
  uint32_t v = p2.properties.apiVersion;
  printf(
    "device: %s (vendor 0x%04x device 0x%04x), Vulkan %u.%u.%u\n",
    p2.properties.deviceName, p2.properties.vendorID, p2.properties.deviceID,
    VK_API_VERSION_MAJOR(v), VK_API_VERSION_MINOR(v), VK_API_VERSION_PATCH(v)
  );
  printf("driver: %s / %s\n", drv.driverName, drv.driverInfo);

  const char* want[] = {
    "VK_ANDROID_native_buffer",
    "VK_ANDROID_external_memory_android_hardware_buffer",
    "VK_KHR_external_memory_fd",
    "VK_EXT_external_memory_dma_buf",
    "VK_EXT_image_drm_format_modifier",
    "VK_EXT_queue_family_foreign",
  };
  const char* enable[8];
  uint32_t nenable = 0;
  for (unsigned i = 0; i < sizeof(want) / sizeof(*want); i++) {
    bool have = has_ext(want[i]);
    printf("  %-52s %s\n", want[i], have ? "yes" : "NO");
    /* Leave out the Android-only extensions: the loader owns those. */
    if (have && strncmp(want[i], "VK_ANDROID_", 11))
      enable[nenable++] = want[i];
  }

  VkQueueFamilyProperties qf[16];
  n = 16;
  vkGetPhysicalDeviceQueueFamilyProperties(pdev, &n, qf);
  qfam = UINT32_MAX;
  for (uint32_t i = 0; i < n && qfam == UINT32_MAX; i++)
    if (
      (qf[i].queueFlags & (VK_QUEUE_GRAPHICS_BIT | VK_QUEUE_COMPUTE_BIT)) ==
      (VK_QUEUE_GRAPHICS_BIT | VK_QUEUE_COMPUTE_BIT)
    )
      qfam = i;
  float prio = 1.0f;
  VkDeviceQueueCreateInfo qci = {
    .sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO,
    .queueFamilyIndex = qfam,
    .queueCount = 1,
    .pQueuePriorities = &prio,
  };
  VkDeviceCreateInfo dci = {
    .sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO,
    .queueCreateInfoCount = 1,
    .pQueueCreateInfos = &qci,
    .enabledExtensionCount = nenable,
    .ppEnabledExtensionNames = enable,
  };
  CHECK(vkCreateDevice(pdev, &dci, NULL, &dev));
  load_device_fns();
  vkGetDeviceQueue(dev, qfam, 0, &queue);
  /* Dispatchable objects from a HAL carry HWVULKAN_DISPATCH_MAGIC for the
   * loader to overwrite; we call the driver directly, so leave it. */

  /* Compute pipeline: data[i] = i * i + seed */
  VkShaderModuleCreateInfo smci = {
    .sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO,
    .codeSize = sizeof(fill_comp),
    .pCode = fill_comp,
  };
  VkShaderModule sm;
  CHECK(vkCreateShaderModule(dev, &smci, NULL, &sm));
  VkDescriptorSetLayoutBinding b = {
    .binding = 0,
    .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
    .descriptorCount = 1,
    .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
  };
  VkDescriptorSetLayoutCreateInfo dslci = {
    .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO,
    .bindingCount = 1,
    .pBindings = &b,
  };
  VkDescriptorSetLayout dsl;
  CHECK(vkCreateDescriptorSetLayout(dev, &dslci, NULL, &dsl));
  VkPushConstantRange pcr = {VK_SHADER_STAGE_COMPUTE_BIT, 0, 8};
  VkPipelineLayoutCreateInfo plci = {
    .sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO,
    .setLayoutCount = 1,
    .pSetLayouts = &dsl,
    .pushConstantRangeCount = 1,
    .pPushConstantRanges = &pcr,
  };
  CHECK(vkCreatePipelineLayout(dev, &plci, NULL, &playout));
  VkComputePipelineCreateInfo cpci = {
    .sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO,
    .stage =
      {
        .sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO,
        .stage = VK_SHADER_STAGE_COMPUTE_BIT,
        .module = sm,
        .pName = "main",
      },
    .layout = playout,
  };
  CHECK(
    vkCreateComputePipelines(dev, VK_NULL_HANDLE, 1, &cpci, NULL, &pipeline)
  );
  VkDescriptorPoolSize ps = {VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 4};
  VkDescriptorPoolCreateInfo dpci = {
    .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO,
    .maxSets = 4,
    .poolSizeCount = 1,
    .pPoolSizes = &ps,
  };
  VkDescriptorPool dp;
  CHECK(vkCreateDescriptorPool(dev, &dpci, NULL, &dp));
  VkDescriptorSetAllocateInfo dsai = {
    .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO,
    .descriptorPool = dp,
    .descriptorSetCount = 1,
    .pSetLayouts = &dsl,
  };
  CHECK(vkAllocateDescriptorSets(dev, &dsai, &dset));
  VkCommandPoolCreateInfo cpi = {
    .sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO,
    .flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT,
    .queueFamilyIndex = qfam,
  };
  VkCommandPool pool;
  CHECK(vkCreateCommandPool(dev, &cpi, NULL, &pool));
  VkCommandBufferAllocateInfo cbai = {
    .sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO,
    .commandPool = pool,
    .level = VK_COMMAND_BUFFER_LEVEL_PRIMARY,
    .commandBufferCount = 1,
  };
  CHECK(vkAllocateCommandBuffers(dev, &cbai, &cmd));
}

static void begin(void) {
  CHECK(vkResetCommandBuffer(cmd, 0));
  VkCommandBufferBeginInfo bi = {
    .sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO,
    .flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT,
  };
  CHECK(vkBeginCommandBuffer(cmd, &bi));
}

static void submit(void) {
  CHECK(vkEndCommandBuffer(cmd));
  VkSubmitInfo si = {
    .sType = VK_STRUCTURE_TYPE_SUBMIT_INFO,
    .commandBufferCount = 1,
    .pCommandBuffers = &cmd,
  };
  CHECK(vkQueueSubmit(queue, 1, &si, VK_NULL_HANDLE));
  CHECK(vkQueueWaitIdle(queue));
}

static VkBuffer make_buffer(
  VkDeviceSize size, VkBufferUsageFlags usage, bool external
) {
  VkExternalMemoryBufferCreateInfo ext = {
    .sType = VK_STRUCTURE_TYPE_EXTERNAL_MEMORY_BUFFER_CREATE_INFO,
    .handleTypes = VK_EXTERNAL_MEMORY_HANDLE_TYPE_DMA_BUF_BIT_EXT,
  };
  VkBufferCreateInfo bci = {
    .sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO,
    .pNext = external ? &ext : NULL,
    .size = size,
    .usage = usage,
  };
  VkBuffer buf;
  CHECK(vkCreateBuffer(dev, &bci, NULL, &buf));
  return buf;
}

/* Run the fill shader over `buf` and return the number of mismatches in `out`.
 */
static uint32_t dispatch_fill(
  VkBuffer buf, uint32_t n, uint32_t seed, volatile uint32_t* out
) {
  VkDescriptorBufferInfo dbi = {buf, 0, VK_WHOLE_SIZE};
  VkWriteDescriptorSet w = {
    .sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET,
    .dstSet = dset,
    .descriptorCount = 1,
    .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
    .pBufferInfo = &dbi,
  };
  vkUpdateDescriptorSets(dev, 1, &w, 0, NULL);
  begin();
  vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
  vkCmdBindDescriptorSets(
    cmd, VK_PIPELINE_BIND_POINT_COMPUTE, playout, 0, 1, &dset, 0, NULL
  );
  uint32_t pc[2] = {n, seed};
  vkCmdPushConstants(cmd, playout, VK_SHADER_STAGE_COMPUTE_BIT, 0, 8, pc);
  vkCmdDispatch(cmd, (n + 63) / 64, 1, 1);
  VkMemoryBarrier mb = {
    .sType = VK_STRUCTURE_TYPE_MEMORY_BARRIER,
    .srcAccessMask = VK_ACCESS_SHADER_WRITE_BIT,
    .dstAccessMask = VK_ACCESS_HOST_READ_BIT,
  };
  vkCmdPipelineBarrier(
    cmd, VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT, VK_PIPELINE_STAGE_HOST_BIT, 0, 1,
    &mb, 0, NULL, 0, NULL
  );
  submit();
  uint32_t bad = 0;
  for (uint32_t i = 0; i < n; i++) bad += out[i] != i * i + seed;
  return bad;
}

static int test_compute(void) {
  const uint32_t n = 1 << 20;
  VkBuffer buf = make_buffer(n * 4, VK_BUFFER_USAGE_STORAGE_BUFFER_BIT, false);
  VkMemoryRequirements mr;
  vkGetBufferMemoryRequirements(dev, buf, &mr);
  VkMemoryAllocateInfo mai = {
    .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
    .allocationSize = mr.size,
    .memoryTypeIndex = find_memtype(
      mr.memoryTypeBits,
      VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT
    ),
  };
  VkDeviceMemory mem;
  CHECK(vkAllocateMemory(dev, &mai, NULL, &mem));
  CHECK(vkBindBufferMemory(dev, buf, mem, 0));
  void* p;
  CHECK(vkMapMemory(dev, mem, 0, VK_WHOLE_SIZE, 0, &p));
  memset(p, 0, n * 4);
  uint32_t bad = dispatch_fill(buf, n, 7, p);
  printf(
    "%s: compute dispatch, %u invocations, data[i] == i*i+7: %u mismatches; "
    "data[1000]=%u\n",
    bad ? "FAIL" : "PASS", n, bad, ((uint32_t*)p)[1000]
  );
  return bad != 0;
}

/* memfd + /dev/udmabuf, the way our gralloc allocates. Returns the dma-buf fd.
 */
static int make_udmabuf(size_t size, int* memfd_out, void** map_out) {
  int memfd = memfd_create("vkdriver_test", MFD_ALLOW_SEALING);
  if (
    memfd < 0 || ftruncate(memfd, size) ||
    fcntl(memfd, F_ADD_SEALS, F_SEAL_SHRINK)
  ) {
    perror("memfd");
    return -1;
  }
  int dev_fd = open("/dev/udmabuf", O_RDWR | O_CLOEXEC);
  if (dev_fd < 0) {
    perror("/dev/udmabuf");
    return -1;
  }
  struct udmabuf_create c = {
    .memfd = memfd, .flags = UDMABUF_FLAGS_CLOEXEC, .offset = 0, .size = size
  };
  int dmabuf = ioctl(dev_fd, UDMABUF_CREATE, &c);
  close(dev_fd);
  if (dmabuf < 0) {
    perror("UDMABUF_CREATE");
    return -1;
  }
  *memfd_out = memfd;
  *map_out = mmap(NULL, size, PROT_READ | PROT_WRITE, MAP_SHARED, memfd, 0);
  return dmabuf;
}

static int test_udmabuf(void) {
  const uint32_t n = 256 * 1024;
  const size_t size = n * 4;
  int memfd;
  void* map;
  int dmabuf = make_udmabuf(size, &memfd, &map);
  if (dmabuf < 0) return 1;
  memset(map, 0xab, size);

  VkMemoryFdPropertiesKHR fdp = {
    .sType = VK_STRUCTURE_TYPE_MEMORY_FD_PROPERTIES_KHR
  };
  VkResult r = vkGetMemoryFdPropertiesKHR(
    dev, VK_EXTERNAL_MEMORY_HANDLE_TYPE_DMA_BUF_BIT_EXT, dmabuf, &fdp
  );
  printf(
    "udmabuf: vkGetMemoryFdPropertiesKHR = %d, memoryTypeBits = 0x%x\n", r,
    fdp.memoryTypeBits
  );

  VkBuffer buf = make_buffer(size, VK_BUFFER_USAGE_STORAGE_BUFFER_BIT, true);
  VkMemoryRequirements mr;
  vkGetBufferMemoryRequirements(dev, buf, &mr);
  uint32_t bits =
    mr.memoryTypeBits & (fdp.memoryTypeBits ? fdp.memoryTypeBits : ~0u);
  uint32_t type = find_memtype(bits, 0);
  VkImportMemoryFdInfoKHR imp = {
    .sType = VK_STRUCTURE_TYPE_IMPORT_MEMORY_FD_INFO_KHR,
    .handleType = VK_EXTERNAL_MEMORY_HANDLE_TYPE_DMA_BUF_BIT_EXT,
    .fd = dmabuf, /* ownership passes to the driver on success */
  };
  VkMemoryAllocateInfo mai = {
    .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
    .pNext = &imp,
    .allocationSize = size,
    .memoryTypeIndex = type,
  };
  VkDeviceMemory mem;
  r = vkAllocateMemory(dev, &mai, NULL, &mem);
  printf("udmabuf: import as memory type %u: vkAllocateMemory = %d\n", type, r);
  if (r != VK_SUCCESS) {
    printf("FAIL: udmabuf import\n");
    return 1;
  }
  CHECK(vkBindBufferMemory(dev, buf, mem, 0));
  uint32_t bad = dispatch_fill(buf, n, 12345, map);
  printf(
    "%s: GPU compute writes into udmabuf, checked via memfd mmap: %u "
    "mismatches of %u\n",
    bad ? "FAIL" : "PASS", bad, n
  );
  return bad != 0;
}

/* --anb-hal: buffer from the hal lane's allocator, imported by
 * mapper.linuxapk.so. */
static const native_handle_t* hal_buffer(
  int width, int height, size_t* stride, size_t* size, void** map
) {
  void* so = dlopen("/data/gputest/libhalbuf.so", RTLD_NOW);
  int (*alloc)(
    int, int, const native_handle_t**, int*, size_t*, void**, size_t*
  ) = so ? dlsym(so, "halbuf_alloc") : NULL;
  const native_handle_t* h = NULL;
  int stride_px;
  if (!alloc || alloc(width, height, &h, &stride_px, stride, map, size) != 0) {
    printf("FAIL: halbuf: %s\n", so ? "allocation" : dlerror());
    exit(1);
  }
  return h;
}

static int anb_stride_px = 128; /* --anb-stride */

static int test_anb(bool hal) {
  const int width = 100, height = 64;
  size_t stride = anb_stride_px * 4,
         size = (stride * height + 4095) & ~4095ul; /* padded rows */
  void* map;
  const native_handle_t* h;
  if (hal) {
    h = hal_buffer(width, height, &stride, &size, &map);
  } else {
    int memfd;
    int dmabuf = make_udmabuf(size, &memfd, &map);
    if (dmabuf < 0) return 1;
    /* gralloc-style handle: fds [dmabuf], ints [magic, w, h, stride_bytes,
     * fourcc] (mock_mapper.c) */
    native_handle_t* mh = calloc(1, sizeof(*mh) + 6 * sizeof(int));
    mh->version = sizeof(native_handle_t);
    mh->numFds = 1;
    mh->numInts = 5;
    mh->data[0] = dmabuf;
    mh->data[1] = 0x4c41504b;
    mh->data[2] = width;
    mh->data[3] = height;
    mh->data[4] = stride;
    mh->data[5] = 0x34324241; /* DRM_FORMAT_ABGR8888 = R8G8B8A8 in memory */
    h = mh;
  }
  memset(map, 0xab, size);

  VkNativeBufferANDROID nb = {
    .sType = VK_STRUCTURE_TYPE_NATIVE_BUFFER_ANDROID,
    .handle = h,
    /* Deliberately wrong (the real row pitch is wider): only the mapper's
     * PLANE_LAYOUTS metadata has the truth, so this passes only if the
     * driver asked the IMapper rather than guessing from the ANB. */
    .stride = width,
    .format = 1,     /* HAL_PIXEL_FORMAT_RGBA_8888 */
    .usage3 = 0x300, /* GPU_TEXTURE | GPU_RENDER_TARGET */
  };
  VkImageCreateInfo ici = {
    .sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO,
    .pNext = &nb,
    .imageType = VK_IMAGE_TYPE_2D,
    .format = VK_FORMAT_R8G8B8A8_UNORM,
    .extent = {width, height, 1},
    .mipLevels = 1,
    .arrayLayers = 1,
    .samples = VK_SAMPLE_COUNT_1_BIT,
    .tiling = VK_IMAGE_TILING_OPTIMAL, /* what libvulkan's swapchain passes */
    .usage =
      VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT,
    .initialLayout = VK_IMAGE_LAYOUT_UNDEFINED,
  };
  VkImage img;
  VkResult r = vkCreateImage(dev, &ici, NULL, &img);
  printf(
    "anb: vkCreateImage(VkNativeBufferANDROID, udmabuf, stride %zu) = %d\n",
    stride, r
  );
  if (r != VK_SUCCESS) {
    printf("FAIL: native buffer import\n");
    return 1;
  }

  /* Upload a pattern (pixel = y << 16 | x) and check it lands at y*stride +
   * x*4. */
  VkBuffer src =
    make_buffer(width * height * 4, VK_BUFFER_USAGE_TRANSFER_SRC_BIT, false);
  VkMemoryRequirements mr;
  vkGetBufferMemoryRequirements(dev, src, &mr);
  VkMemoryAllocateInfo mai = {
    .sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
    .allocationSize = mr.size,
    .memoryTypeIndex = find_memtype(
      mr.memoryTypeBits,
      VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT
    ),
  };
  VkDeviceMemory smem;
  CHECK(vkAllocateMemory(dev, &mai, NULL, &smem));
  CHECK(vkBindBufferMemory(dev, src, smem, 0));
  uint32_t* sp;
  CHECK(vkMapMemory(dev, smem, 0, VK_WHOLE_SIZE, 0, (void**)&sp));
  for (int y = 0; y < height; y++)
    for (int x = 0; x < width; x++) sp[y * width + x] = (uint32_t)y << 16 | x;

  begin();
  VkImageMemoryBarrier ib = {
    .sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER,
    .dstAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT,
    .oldLayout = VK_IMAGE_LAYOUT_UNDEFINED,
    .newLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
    .srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
    .dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED,
    .image = img,
    .subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1},
  };
  vkCmdPipelineBarrier(
    cmd, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, 0,
    0, NULL, 0, NULL, 1, &ib
  );
  VkBufferImageCopy copy = {
    .imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1},
    .imageExtent = {width, height, 1},
  };
  vkCmdCopyBufferToImage(
    cmd, src, img, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &copy
  );
  /* Hand the buffer to the "presenter": general layout, foreign queue, host
   * visible. */
  ib.srcAccessMask = VK_ACCESS_TRANSFER_WRITE_BIT;
  ib.dstAccessMask = VK_ACCESS_HOST_READ_BIT | VK_ACCESS_MEMORY_READ_BIT;
  ib.oldLayout = VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
  ib.newLayout = VK_IMAGE_LAYOUT_GENERAL;
  vkCmdPipelineBarrier(
    cmd, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_HOST_BIT, 0, 0, NULL,
    0, NULL, 1, &ib
  );
  submit();

  const uint8_t* m = map;
  uint32_t bad = 0, pad_bad = 0;
  for (int y = 0; y < height; y++) {
    for (int x = 0; x < width; x++) {
      uint32_t v;
      memcpy(&v, m + y * stride + x * 4, 4);
      bad += v != ((uint32_t)y << 16 | x);
    }
    for (size_t b = width * 4; b < stride; b++)
      pad_bad += m[y * stride + b] != 0xab;
  }
  uint32_t probe;
  memcpy(&probe, m + 37 * stride + 42 * 4, 4);
  printf(
    "%s: gralloc-handle image written by GPU copy, read via memfd: %u pixel "
    "mismatches, "
    "%u padding bytes touched; pixel(42,37)=0x%08x\n",
    bad || pad_bad ? "FAIL" : "PASS", bad, pad_bad, probe
  );
  return bad || pad_bad;
}

int main(int argc, char** argv) {
  const char* hal = "vulkan.radv.so"; /* bare name, as libvulkan does */
  bool loader = false, udmabuf = false, anb = false, anb_hal = false;
  for (int i = 1; i < argc; i++) {
    if (!strcmp(argv[i], "--hal") && i + 1 < argc)
      hal = argv[++i];
    else if (!strcmp(argv[i], "--loader"))
      loader = true;
    else if (!strcmp(argv[i], "--udmabuf"))
      udmabuf = true;
    else if (!strcmp(argv[i], "--anb"))
      anb = true;
    else if (!strcmp(argv[i], "--anb-stride") && i + 1 < argc)
      anb_stride_px = atoi(argv[++i]);
    else if (!strcmp(argv[i], "--anb-hal"))
      anb_hal = true;
  }
  setup_device(loader ? open_loader() : open_hal(hal));
  int fails = test_compute();
  if (udmabuf) fails += test_udmabuf();
  if (anb) fails += test_anb(false);
  if (anb_hal) fails += test_anb(true);
  printf("%s\n", fails ? "SOME TESTS FAILED" : "ALL PASSED");
  return fails != 0;
}
